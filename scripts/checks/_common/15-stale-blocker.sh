#!/usr/bin/env bash
# 判据（路签同形，2026-07-30 用户点破「过期便条该自堵不该巡逻」）：
# blockers/<id>.md = 一张「在等裁决/在阻塞」的便条，必须写明「解除标志：」——
# 一个仓内路径，或 <文字>@<文件>。标志一出现，本检查变红：**障已解未销**，
# 做完决定的那笔提交必须同批删掉便条，否则冷启动 agent 会停等一个已做完的决定
# （实证三例：§4.1 待改清单、nexus-core「等 CFO 裁决」、阻塞标记——全是解了没销）。
[ "${1:-}" = --describe ] && { echo "15 障签：blockers/ 便条的解除标志已出现则必须同批销障（过期便条自堵，不靠人巡逻）"; exit 0; }
set -uo pipefail
#
# 2026-08-11 修（P1，CFO 波2 里程碑审计实证）：判据从建仓至今对项目实际使用的
# 「`` `文字` @ `文件` ``」反引号写法恒假 —— `${mark%@*}`/`${mark##*@}` 切完，
# 残留的反引号与前导空格原样留在 `_file` 里，`[ -f "$_file" ]` 永远找不到那个文件。
# 现场证据：blockers/2026-08-02-e2e-defaults-to-prod.md 的解除标志已经满足，
# 本检查改前仍 exit 0（该红不红——铁律 23 点名的最坏形状：静默跳过后报成功）。
#
# 修法两层：① 剥掉反引号与前后空白再判定；② 剥完仍不是「干净路径」（还带
# 反引号/空白/全角标点等）就判定「解除标志格式不受支持」并主动置红——
# 不让它退化成「永远 met=0、永远不会自己销」的第二种静默假绿。
_trim() {   # 剥外层空白 → 外层一对反引号 → 再剥一次空白（`` ` foo ` `` → foo）
  printf '%s' "$1" | sed -E 's/^[[:space:]]*//; s/[[:space:]]*$//; s/^`//; s/`$//; s/^[[:space:]]*//; s/[[:space:]]*$//'
}
_clean_path() {   # 剥干净后仍带反引号/空白/全角标点 → 不是一个能拿去 -f/-e 判的路径
  case "$1" in *'`'*|*[[:space:]]*|*'（'*|*'）'*|*'，'*) return 1 ;; esac
  [ -n "$1" ]
}
fail=0
while IFS= read -r -d '' b; do
  [ -f "$b" ] || continue
  mark=$(grep -m1 '^解除标志：' "$b" | sed 's/^解除标志：//; s/^[[:space:]]*//; s/[[:space:]]*$//')
  if [ -z "$mark" ]; then
    echo "$b 没写「解除标志：」——没有解除标志的障永远销不掉，等于把便条钉死" >&2
    fail=1; continue
  fi
  met=0
  case "$mark" in
    *@*)
      _pat=$(_trim "${mark%@*}"); _file=$(_trim "${mark##*@}")
      if ! _clean_path "$_file" || [ -z "$_pat" ]; then
        echo "$b 的解除标志格式不受支持（<文字>@<文件> 中 <文件> 剥掉反引号/空白后仍不是干净路径）：$mark" >&2
        echo "  → 这种标志永远判不出「已解除」，等于把便条钉死——改成 \`文字\` @ \`仓内/路径\`" >&2
        fail=1; continue
      fi
      [ -f "$_file" ] && grep -qF -- "$_pat" "$_file" && met=1 ;;
    *)
      _p=$(_trim "$mark")
      if ! _clean_path "$_p"; then
        echo "$b 的解除标志格式不受支持（既不是 <文字>@<文件>，剥掉反引号/空白后也不是干净的仓内路径）：$mark" >&2
        echo "  → 这种标志永远判不出「已解除」，等于把便条钉死——改成一个仓内路径或 \`文字\` @ \`文件\`" >&2
        fail=1; continue
      fi
      [ -e "$_p" ] && met=1 ;;
  esac
  if [ "$met" -eq 1 ]; then
    echo "障已解未销：$b 的解除标志（$mark）已出现——随本次提交删除这张便条" >&2
    echo "  → 过期便条比没便条更糟：下一个人会停等一个已做完的决定" >&2
    fail=1
  fi
done < <(git ls-files -z 'blockers/*.md' 2>/dev/null)
exit $fail
